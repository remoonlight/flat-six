/** Verified Windows binary reuse and explicit diagnostic script staging. */
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";

const electronFiles = new Set(["FlatSix.exe", "LICENSE", "LICENSES.chromium.html", "chrome_100_percent.pak",
  "chrome_200_percent.pak", "d3dcompiler_47.dll", "ffmpeg.dll", "icudtl.dat", "libEGL.dll", "libGLESv2.dll",
  "resources.pak", "snapshot_blob.bin", "v8_context_snapshot.bin", "version", "vk_swiftshader.dll",
  "vk_swiftshader_icd.json", "vulkan-1.dll", "resources/default_app.asar"]);
const runtimePrefix = "resources/app/runtime/";
export const sha256 = (file) => createHash("sha256").update(fs.readFileSync(file)).digest("hex");
const diagnosticScriptFiles = ["scripts/__init__.py", "scripts/run-x431-reference.py",
  "scripts/run-x431-version.py", "scripts/run-x431-response.py", "scripts/run-x431-command.py",
  "scripts/run-x431-native-binding.py", "scripts/run-x431-selector-gap.py",
  "scripts/run-manufacturer-read.py", "scripts/run-x431-command-reference.py",
  "scripts/run-x431-loader-reference.py", "scripts/run-x431-command-caller-reference.py"];

export function safeFile(root, relative) {
  if (typeof relative !== "string" || !relative || relative.includes("\\") || relative.includes(":") ||
      relative.split("/").some((part) => !part || part === "." || part === "..") || path.posix.isAbsolute(relative))
    throw new Error("runtime-source-path-invalid");
  let current = root;
  for (const part of relative.split("/")) {
    current = path.join(current, part);
    if (fs.lstatSync(current).isSymbolicLink()) throw new Error("runtime-source-symlink-excluded");
  }
  if (!fs.statSync(current).isFile()) throw new Error("runtime-source-file-invalid");
  return current;
}

export function copyDiagnosticScriptEntries(source, target) {
  for (const name of diagnosticScriptFiles) {
    const input = safeFile(source, name), output = path.join(target, ...name.split("/"));
    fs.mkdirSync(path.dirname(output), { recursive: true });
    fs.writeFileSync(output, fs.readFileSync(input), { flag: "wx" });
  }
}

function isRuntimeFile(name) {
  // Bytecode was generated by the old probe and omitted during migration.
  // Rebuild it on the target; never treat cache files as runtime source.
  if (name.split("/").includes("__pycache__") || name.endsWith(".pyc")) return false;
  return electronFiles.has(name) || /^locales\/[a-zA-Z0-9_-]+\.pak$/.test(name) ||
    name === `${runtimePrefix}node.exe` || name === `${runtimePrefix}NODE-LICENSE.txt` ||
    name.startsWith(`${runtimePrefix}python/`);
}

function requireX64(file) {
  const fd = fs.openSync(file, "r");
  try {
    const header = Buffer.alloc(64), pe = Buffer.alloc(6);
    if (fs.readSync(fd, header, 0, 64, 0) !== 64 || header.toString("ascii", 0, 2) !== "MZ" ||
        fs.readSync(fd, pe, 0, 6, header.readUInt32LE(0x3c)) !== 6 ||
        pe.readUInt32LE(0) !== 0x4550 || pe.readUInt16LE(4) !== 0x8664)
      throw new Error("runtime-source-not-Windows-x64");
  } finally { fs.closeSync(fd); }
}

export function verifyRuntimeSource(source, electronVersion) {
  const root = path.resolve(source);
  if (fs.lstatSync(root).isSymbolicLink()) throw new Error("runtime-source-symlink-excluded");
  const manifestFile = safeFile(root, "delivery-manifest.json");
  const manifest = JSON.parse(fs.readFileSync(manifestFile, "utf8"));
  if (manifest.kind !== "local-windows-unpacked-delivery" || manifest.bundledRuntimes !== true ||
      manifest.privateDefinitionsIncluded !== false || manifest.driversIncluded !== false || !Array.isArray(manifest.files))
    throw new Error("runtime-source-manifest-invalid");
  const seen = new Set(), selected = [];
  for (const row of manifest.files) {
    // Reject duplicates even in excluded app files; a chosen binding must be unique.
    if (typeof row.path !== "string" || seen.has(row.path)) throw new Error("runtime-source-manifest-duplicate");
    seen.add(row.path);
    if (!isRuntimeFile(row.path)) continue;
    const file = safeFile(root, row.path);
    if (!Number.isSafeInteger(row.bytes) || row.bytes < 0 || !/^[a-f0-9]{64}$/.test(row.sha256 || "") ||
        fs.statSync(file).size !== row.bytes || sha256(file) !== row.sha256)
      throw new Error(`runtime-source-integrity-failed:${row.path}`);
    selected.push({ ...row, file });
  }
  for (const name of ["FlatSix.exe", "version", `${runtimePrefix}node.exe`, `${runtimePrefix}python/python.exe`])
    if (!selected.some((row) => row.path === name)) throw new Error(`runtime-source-required-file-missing:${name}`);
  if (fs.readFileSync(safeFile(root, "version"), "utf8").trim().replace(/^v/, "") !== electronVersion)
    throw new Error("runtime-source-electron-version-mismatch");
  for (const name of ["FlatSix.exe", `${runtimePrefix}node.exe`, `${runtimePrefix}python/python.exe`]) requireX64(safeFile(root, name));
  return { root, files: selected, manifestSha256: sha256(manifestFile), electronVersion };
}

export function copyVerifiedRuntime(verified, target) {
  for (const row of verified.files) {
    // Read and recheck before each publish; source can have changed since verification.
    const input = safeFile(verified.root, row.path), output = path.join(target, ...row.path.split("/"));
    const data = fs.readFileSync(input);
    if (data.length !== row.bytes || createHash("sha256").update(data).digest("hex") !== row.sha256)
      throw new Error(`runtime-source-changed:${row.path}`);
    fs.mkdirSync(path.dirname(output), { recursive: true });
    fs.writeFileSync(output, data, { flag: "wx" });
  }
}
