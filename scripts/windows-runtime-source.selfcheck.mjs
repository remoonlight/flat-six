import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { verifyRuntimeSource, copyVerifiedRuntime, copyDiagnosticScriptEntries, sha256 } from "./windows-runtime-source.mjs";

const temp = fs.mkdtempSync(path.join(os.tmpdir(), "flat-six-retained-runtime-"));
const source = path.join(temp, "source"); fs.mkdirSync(source);
const pe = Buffer.alloc(128); pe.write("MZ"); pe.writeUInt32LE(64, 0x3c); pe.writeUInt32LE(0x4550, 64); pe.writeUInt16LE(0x8664, 68);
const inputs = { "FlatSix.exe": pe, "version": "34.5.8", "resources/app/runtime/node.exe": pe,
  "resources/app/runtime/python/python.exe": pe, "resources/app/runtime/python/Lib/site.py": "# fixture",
  "resources/app/private.db": "private database", "resources/app/runtime/python/Lib/site-packages/serial/__init__.py": "VERSION='3.5'" };
for (const [name, data] of Object.entries(inputs)) {
  const file = path.join(source, name); fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, data);
}
const manifest = { kind: "local-windows-unpacked-delivery", bundledRuntimes: true,
  privateDefinitionsIncluded: false, driversIncluded: false,
  files: Object.keys(inputs).map((name) => ({ path: name, bytes: fs.statSync(path.join(source, name)).size, sha256: sha256(path.join(source, name)) })) };
// Old probe's generated bytecode is deliberately absent after migration.
manifest.files.push({ path: "resources/app/runtime/python/Lib/__pycache__/site.cpython-314.pyc", bytes: 1, sha256: "0".repeat(64) });
const manifestFile = path.join(source, "delivery-manifest.json");
const reset = (value = manifest) => fs.writeFileSync(manifestFile, JSON.stringify(value));
try {
  const projectRoot = path.resolve(import.meta.dirname, "..");
  const scriptOutput = path.join(temp, "script-entries");
  copyDiagnosticScriptEntries(projectRoot, scriptOutput);
  const expectedScripts = fs.readdirSync(path.join(projectRoot, "scripts"))
    .filter((name) => /^run-x431-[a-z-]+\.py$/.test(name) || name === "run-manufacturer-read.py")
    .concat("__init__.py").sort();
  assert.deepEqual(fs.readdirSync(path.join(scriptOutput, "scripts")).sort(), expectedScripts,
    "every standalone diagnostic entry ships with its installed modules");
  for (const name of expectedScripts)
    assert.equal(sha256(path.join(scriptOutput, "scripts", name)), sha256(path.join(projectRoot, "scripts", name)));
  assert.throws(() => copyDiagnosticScriptEntries(projectRoot, scriptOutput), /EEXIST/);
  assert.throws(() => copyDiagnosticScriptEntries(source, path.join(temp, "missing-entries")), /ENOENT/);
  reset(); const verified = verifyRuntimeSource(source, "34.5.8");
  assert.equal(verified.files.length, 6);
  const output = path.join(temp, "output"); copyVerifiedRuntime(verified, output);
  assert.equal(fs.existsSync(path.join(output, "resources/app/private.db")), false, "never migrate app or private data from old delivery");
  assert.equal(fs.existsSync(path.join(output, "resources/app/runtime/python/Lib/__pycache__")), false);
  assert.equal(sha256(path.join(output, "FlatSix.exe")), sha256(path.join(source, "FlatSix.exe")));
  assert.throws(() => copyVerifiedRuntime(verified, output), /EEXIST/, "old output is never overwritten");
  assert.throws(() => verifyRuntimeSource(source, "35.0.0"), /version-mismatch/);
  reset({ ...manifest, driversIncluded: true }); assert.throws(() => verifyRuntimeSource(source, "34.5.8"), /manifest-invalid/);
  reset({ ...manifest, files: [...manifest.files, manifest.files[0]] }); assert.throws(() => verifyRuntimeSource(source, "34.5.8"), /duplicate/);
  reset({ ...manifest, files: manifest.files.filter((row) => row.path !== "resources/app/runtime/node.exe") });
  assert.throws(() => verifyRuntimeSource(source, "34.5.8"), /required-file-missing/);
  reset({ ...manifest, files: [...manifest.files, { path: "resources/app/runtime/python/../private.db", bytes: 0, sha256: "0".repeat(64) }] });
  assert.throws(() => verifyRuntimeSource(source, "34.5.8"), /path-invalid/);
  reset();
  const site = path.join(source, "resources/app/runtime/python/Lib/site.py");
  fs.writeFileSync(site, "# changed");
  assert.throws(() => verifyRuntimeSource(source, "34.5.8"), /integrity-failed/);
  assert.throws(() => copyVerifiedRuntime(verified, path.join(temp, "changed-output")), /source-changed/);
  fs.writeFileSync(site, inputs["resources/app/runtime/python/Lib/site.py"]);
  fs.renameSync(site, `${site}.original`); fs.symlinkSync(`${site}.original`, site);
  assert.throws(() => verifyRuntimeSource(source, "34.5.8"), /symlink-excluded/);
  fs.unlinkSync(site); fs.renameSync(`${site}.original`, site);
  const invalidPe = Buffer.from(pe); invalidPe.writeUInt16LE(0x14c, 68);
  fs.writeFileSync(path.join(source, "FlatSix.exe"), invalidPe);
  reset({ ...manifest, files: manifest.files.map((row) => row.path === "FlatSix.exe" ? { ...row, sha256: sha256(path.join(source, row.path)) } : row) });
  assert.throws(() => verifyRuntimeSource(source, "34.5.8"), /not-Windows-x64/);
  console.log("windows-runtime-source.selfcheck: ok (private exclusion, drift, duplicate, version, architecture, symlink and exclusive output)");
} finally { fs.rmSync(temp, { recursive: true }); }
