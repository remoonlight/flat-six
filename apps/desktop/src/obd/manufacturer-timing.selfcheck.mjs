import assert from "node:assert/strict";
import { manufacturerTiming, manufacturerConnectionMessage } from "./manufacturer-timing.mjs";
const value = (elapsedMs, connectionEpoch = 1, extra = {}) => ({ elapsedMs, connectionEpoch, numeric: true, value: 42, ...extra });
assert.deepEqual(manufacturerTiming([]), { segments: [], points: [], intervalMs: null, recovered: false, interruptions: 0 });
assert.equal(manufacturerTiming([value(12)]).intervalMs, null);
const steady = [value(12), value(1142), value(3876)];
assert.equal(manufacturerTiming(steady).intervalMs, 2734);
assert.deepEqual(manufacturerTiming(steady).segments, [steady]);
const recovery = [value(12), value(1142), value(9800, 2), value(10935, 2)];
const split = manufacturerTiming(recovery);
assert.deepEqual(split.segments, [recovery.slice(0, 2), recovery.slice(2)]);
assert.equal(split.intervalMs, 1135); assert.equal(split.interruptions, 1);
assert.equal(manufacturerTiming(recovery.slice(0, 3)).intervalMs, null);
assert.equal(manufacturerTiming(recovery.slice(0, 3)).recovered, true);
const rollback = [value(100), value(50)];
assert.equal(manufacturerTiming(rollback).segments.length, 2);
assert.equal(manufacturerTiming(rollback).intervalMs, null);
const text = [value(0), value(500, 1, { numeric: false, value: "关闭" }), value(1000)];
assert.deepEqual(manufacturerTiming(text).segments, [[text[0]], [text[2]]]);
assert.equal(manufacturerTiming(text).points.length, 2);
const legacy = [{ ...value(0), connectionEpoch: undefined }, { ...value(1200), connectionEpoch: undefined }];
assert.equal(manufacturerTiming(legacy).intervalMs, 1200);
assert.equal(manufacturerTiming(legacy).interruptions, 0);
assert.equal(manufacturerTiming([value(0), value(NaN)]).intervalMs, null);
assert.equal(manufacturerTiming([value(0), value(Infinity)]).points.length, 1);
assert.deepEqual(recovery.map(s => s.elapsedMs), [12, 1142, 9800, 10935], "no inserted samples or input mutation");
console.log("PASS manufacturer host observation intervals, reconnect segments, text/time gaps and legacy observations");
assert.equal(manufacturerConnectionMessage(null), "");
assert.match(manufacturerConnectionMessage({ phase: "retrying", attempt: 2, reason: null }), /第 2\/3 次重连/);
assert.match(manufacturerConnectionMessage({ phase: "qualified", attempt: 1, reason: null }), /等待未完成请求的响应/);
assert.doesNotMatch(manufacturerConnectionMessage({ phase: "qualified", attempt: 1, reason: null }), /已恢复/);
assert.match(manufacturerConnectionMessage({ phase: "failed", attempt: 1, reason: "identity-mismatch" }), /身份不符/);
assert.match(manufacturerConnectionMessage({ phase: "failed", attempt: 1, reason: "cancelled" }), /取消/);
assert.match(manufacturerConnectionMessage({ phase: "failed", attempt: 1, reason: "deadline-expired" }), /期限/);
assert.equal(manufacturerConnectionMessage({ phase: "unknown", attempt: 1, reason: null }), "");
assert.match(manufacturerConnectionMessage({ phase: "retrying", attempt: 1, reason: null }, true), /本批已结束.*未确认/);
console.log("PASS manufacturer recovery messages distinguish qualified identity, received answer and terminal failure");
